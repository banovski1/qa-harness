// Renders the four markdown reports from screens/*.json and network.json.
// Nothing under app-analysis/ is hand-written: the fix for a wrong report is to
// re-run the phase that produced its input.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// The ladder is defined once, in the fragment that ranks with it. Reading it
// back from that file is what stops this report and the extractor from drifting
// apart — a rung added there appears here without an edit.
const ladderSource = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'rank-locators.js'), 'utf8');
const LADDER = [...ladderSource.matchAll(/var LADDER = \[([\s\S]*?)\]/g)][0][1]
  .split(',').map((entry) => entry.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);
const SEMANTIC = [...ladderSource.matchAll(/var SEMANTIC_STRATEGIES = \[([\s\S]*?)\]/g)][0][1]
  .split(',').map((entry) => entry.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);

const escapeCell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 120);

function provenance(profile, extra) {
  return [
    '<!-- generated by .claude/skills/app-explorer — do not hand-edit -->',
    '',
    `- **App:** ${profile.name || profile.baseUrl}`,
    `- **Base URL:** ${profile.baseUrl}`,
    `- **Generated:** ${new Date().toISOString()}`,
    ...extra,
    '',
  ].join('\n');
}

// A record id in a path is a slot, not identity, so the same endpoint reached
// with a thousand ids collapses to one row.
function templatePath(url) {
  try {
    const parsed = new URL(url);
    const path = parsed.pathname
      .replace(/\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}(?=\/|$)/gi, '/{id}')
      .replace(/\/[0-9a-f]{16,}(?=\/|$)/gi, '/{id}')
      .replace(/\/\d+(?=\/|$)/g, '/{id}');
    return { path, params: [...parsed.searchParams.keys()] };
  } catch {
    return { path: url, params: [] };
  }
}

function shapeKeys(shape, prefix = '', depth = 0) {
  if (depth > 2 || shape === null || typeof shape !== 'object') return [];
  if (Array.isArray(shape)) return shape.length ? shapeKeys(shape[0], prefix + '[]', depth + 1) : [];
  const out = [];
  for (const [key, value] of Object.entries(shape)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === 'object') out.push(...shapeKeys(value, path, depth + 1));
    else out.push(`${path}: ${value}`);
  }
  return out;
}

async function loadScreens(outDir) {
  const dir = join(outDir, 'screens');
  if (!existsSync(dir)) return [];
  const files = (await readdir(dir)).filter((f) => f.endsWith('.json')).sort();
  const screens = [];
  for (const file of files) {
    screens.push({ id: file.replace(/\.json$/, ''), ...JSON.parse(await readFile(join(dir, file), 'utf8')) });
  }
  return screens;
}

function renderInventory(screens, state, profile) {
  const lines = [
    '# Screen inventory',
    '',
    provenance(profile, [
      `- **Screens crawled:** ${screens.length}`,
      `- **Screens failed:** ${Object.keys(state.failed || {}).length}`,
    ]),
    'Counts are over **visible** controls. Hidden controls (collapsed menus, closed',
    'dropdowns) are extracted into `screens/*.json` but excluded from these totals,',
    'because a locator for something the user cannot see is not one a test can act on.',
    '',
    '| Screen | Title | URL | Visible | Semantic | Fragile | Ambiguous | Hidden | Settled |',
    '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- |',
  ];
  for (const screen of screens) {
    const visited = (state.visited || {})[screen.id] || {};
    const s = screen.stats;
    lines.push(`| \`${screen.id}\` | ${escapeCell(screen.title)} | ${escapeCell(screen.url)} | ${s.visible} | ${s.semantic} | ${s.fragile} | ${s.ambiguous} | ${s.hidden} | ${visited.settled ? 'yes' : 'no'} |`);
  }

  const failed = Object.entries(state.failed || {});
  lines.push('', '## Screens that did not yield', '');
  if (!failed.length) lines.push('None. Every queued screen was extracted.');
  else {
    lines.push('| Screen | URL | Reason |', '| --- | --- | --- |');
    for (const [id, info] of failed) {
      lines.push(`| \`${id}\` | ${escapeCell(info.url)} | ${escapeCell(info.error)} |`);
    }
  }

  lines.push('', '## Per-screen detail', '');
  for (const screen of screens) {
    lines.push(`### \`${screen.id}\``, '');
    lines.push(`- URL: ${screen.url}`);
    if (screen.headings.length) lines.push(`- Headings: ${screen.headings.map((h) => `\`${h.text}\``).join(', ')}`);
    lines.push(`- Regions: ${Object.entries(screen.regions).map(([k, v]) => `${k} (${v})`).join(', ') || 'none'}`);
    for (const table of screen.tables) {
      if (table.columns.length) lines.push(`- Table columns: ${table.columns.map((c) => `\`${c}\``).join(', ')} — ${table.rowCount} rows`);
    }
    lines.push('');
  }
  return lines.join('\n') + '\n';
}

// A component is a region signature that recurs: the same role/name set showing
// up on many screens is app chrome, and belongs in one shared page object.
function renderComponents(screens, profile) {
  const byRegion = new Map();
  for (const screen of screens) {
    const grouped = new Map();
    for (const element of screen.elements) {
      if (!element.visible) continue;
      if (!grouped.has(element.region)) grouped.set(element.region, []);
      grouped.get(element.region).push(element);
    }
    for (const [region, elements] of grouped) {
      // The signature is the region's *shape* — which roles it holds and how
      // many — not the names inside it. A list toolbar is the same component on
      // the contacts screen and the invoices screen; keying on names would call
      // those two different things and report nothing as shared.
      const shape = {};
      for (const element of elements) {
        const role = element.role || element.tag;
        shape[role] = (shape[role] || 0) + 1;
      }
      const signature = region + '::' + Object.entries(shape).sort().map(([role, count]) => `${role}x${count}`).join('|');
      if (!byRegion.has(signature)) {
        byRegion.set(signature, { region, elements, screens: [], shape });
      }
      byRegion.get(signature).screens.push(screen.id);
    }
  }

  const groups = [...byRegion.values()].sort((a, b) => b.screens.length - a.screens.length);
  const shared = groups.filter((g) => g.screens.length > 1);
  const unique = groups.filter((g) => g.screens.length === 1);

  const lines = [
    '# Component analysis',
    '',
    provenance(profile, [
      `- **Recurring components:** ${shared.length}`,
      `- **Screen-specific regions:** ${unique.length}`,
      `- **Screens covered:** ${screens.length}`,
    ]),
    'A component here is a region whose *shape* recurs across screens — the roles it',
    'contains and how many, independent of the names inside it, so the same toolbar',
    'is recognised on the contacts screen and the invoices screen alike.',
    '',
    'Anything appearing on more than one screen belongs in a shared page object;',
    'anything appearing once belongs to that screen.',
    '',
    '## Shared across screens',
    '',
  ];
  if (!shared.length) lines.push('No region signature recurred across screens.');
  for (const group of shared.slice(0, 40)) {
    lines.push(`### ${group.region} — the same shape on ${group.screens.length} screens`, '');
    lines.push(`Shape: ${Object.entries(group.shape).sort().map(([role, count]) => `${count}× ${role}`).join(', ')}`, '');
    lines.push(`Screens: ${group.screens.slice(0, 12).map((s) => `\`${s}\``).join(', ')}${group.screens.length > 12 ? ', …' : ''}`, '');
    lines.push(`Elements below are from \`${group.screens[0]}\`; the other screens carry the same controls with their own names.`, '');
    lines.push('| Element | Role | Locator | Quality |', '| --- | --- | --- | --- |');
    for (const element of group.elements.slice(0, 25)) {
      const quality = !element.unique ? 'ambiguous' : element.fragile ? 'css fallback' : 'semantic';
      lines.push(`| ${escapeCell(element.name || element.tag)} | ${element.role || element.tag} | \`${escapeCell(element.locator ? element.locator.expression : '—')}\` | ${quality} |`);
    }
    lines.push('');
  }

  lines.push('## Screen-specific regions', '');
  lines.push('| Screen | Region | Elements |', '| --- | --- | ---: |');
  for (const group of unique) {
    lines.push(`| \`${group.screens[0]}\` | ${group.region} | ${group.elements.length} |`);
  }
  return lines.join('\n') + '\n';
}

function renderLocators(screens, profile) {
  const tally = Object.fromEntries(LADDER.map((rung) => [rung, 0]));
  let total = 0;
  let semantic = 0;
  const weakRows = [];
  for (const screen of screens) {
    for (const element of screen.elements) {
      if (!element.visible) continue;
      total++;
      if (element.locator) tally[element.locator.strategy]++;
      if (element.unique && !element.fragile) semantic++;
      else weakRows.push({ screen: screen.id, element });
    }
  }

  const lines = [
    '# Locator strategy',
    '',
    provenance(profile, [
      `- **Visible interactive controls:** ${total}`,
      `- **Addressable semantically:** ${semantic} (${total ? Math.round((semantic / total) * 100) : 0}%)`,
      `- **Needing a CSS path or still ambiguous:** ${total - semantic}`,
    ]),
    'Every candidate below was counted against the live DOM at extraction time, so',
    '"resolves uniquely" means exactly one element on the rendered page answered to',
    'it — not that it looked unique in source.',
    '',
    'A bare CSS path always resolves to one element, so it is never counted as a',
    'semantic result. Those rows are the fragile ones: they break the moment the',
    'markup around them is rearranged, and they are listed in full below.',
    '',
    '## The ladder, best to worst',
    '',
    '| Rung | Strategy | Semantic | Chosen for |',
    '| ---: | --- | --- | ---: |',
    ...LADDER.map((rung, i) => `| ${i + 1} | \`${rung}\` | ${SEMANTIC.includes(rung) ? 'yes' : 'no'} | ${tally[rung]} |`),
    '',
    '## Recommendation',
    '',
    tally.testId > total * 0.5
      ? `This app carries test ids on most controls — address elements with \`getByTestId\` and treat anything below that rung as a gap to report upstream.`
      : `Only ${tally.testId} of ${total} visible controls carry a test id, so the working default is \`getByRole\` with an exact accessible name (${tally.role} controls), falling back to \`getByLabel\` inside forms (${tally.label}) and \`getByPlaceholder\` (${tally.placeholder}).`,
    '',
    `Where a control has no name of its own, ${tally.scoped} were reachable through an ancestor the application names deliberately — \`[data-name="…"] input\` and the like. That is a CSS expression anchored to a semantic attribute, so it survives restyling and breaks only when the field is renamed. Prefer it over a markup path every time.`,
    '',
    `A bare markup path was the only option left for ${tally.css} controls. Each is a control with no test id, no accessible name, no label, no placeholder and no named ancestor. Those are the ones to fix in the application — and, until then, the ones to wrap in a page object so a single markup change costs one edit rather than many.`,
    '',
    '## Controls without a semantic locator',
    '',
  ];
  if (!weakRows.length) lines.push('None. Every visible control resolved through a semantic locator.');
  else {
    lines.push('| Screen | Control | Role | Chosen locator | Matches | Why |', '| --- | --- | --- | --- | ---: | --- |');
    for (const row of weakRows.slice(0, 200)) {
      const best = row.element.locator;
      lines.push(`| \`${row.screen}\` | ${escapeCell(row.element.name || row.element.tag)} | ${row.element.role || row.element.tag} | \`${escapeCell(best ? best.expression : '—')}\` | ${best ? best.matchCount : 0} | ${escapeCell(row.element.ambiguityReason)} |`);
    }
    if (weakRows.length > 200) lines.push('', `…and ${weakRows.length - 200} more, in \`screens/*.json\`.`);
  }
  lines.push('', '## Full element map', '', 'Every element, its chosen locator and its alternatives, is in `screens/<screen>.json` under `elements[]`. That file is the machine-readable contract; this document is its summary.', '');
  return lines.join('\n') + '\n';
}

function renderApi(network, spec, profile) {
  const endpoints = new Map();
  for (const entry of network) {
    const { path, params } = templatePath(entry.url);
    const key = `${entry.method} ${path}`;
    if (!endpoints.has(key)) {
      endpoints.set(key, {
        method: entry.method, path, calls: 0, statuses: new Set(),
        params: new Set(), screens: new Set(), requestShape: null, responseShape: null,
      });
    }
    const endpoint = endpoints.get(key);
    endpoint.calls++;
    endpoint.statuses.add(entry.status);
    params.forEach((p) => endpoint.params.add(p));
    if (entry.screen) endpoint.screens.add(entry.screen);
    if (!endpoint.requestShape && entry.requestShape) endpoint.requestShape = entry.requestShape;
    if (!endpoint.responseShape && entry.responseShape) endpoint.responseShape = entry.responseShape;
  }

  const rows = [...endpoints.values()].sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  const lines = [
    '# API documentation',
    '',
    provenance(profile, [
      `- **Endpoints observed:** ${rows.length}`,
      `- **Calls recorded:** ${network.length}`,
      `- **Specification discovered:** ${spec ? spec.url : 'none'}`,
    ]),
    'Every endpoint here was observed being called by the application itself while',
    'the crawl ran. Request and response bodies are recorded as keys and types only;',
    'no value from the app reaches this file.',
    '',
    '## Endpoints',
    '',
    '| Method | Path | Calls | Statuses | Query params | Seen on |',
    '| --- | --- | ---: | --- | --- | --- |',
  ];
  for (const row of rows) {
    lines.push(`| \`${row.method}\` | \`${row.path}\` | ${row.calls} | ${[...row.statuses].join(', ')} | ${[...row.params].map((p) => `\`${p}\``).join(', ') || '—'} | ${[...row.screens].slice(0, 4).map((s) => `\`${s}\``).join(', ')}${row.screens.size > 4 ? ', …' : ''} |`);
  }

  lines.push('', '## Payload shapes', '');
  for (const row of rows) {
    if (!row.requestShape && !row.responseShape) continue;
    lines.push(`### \`${row.method} ${row.path}\``, '');
    if (row.requestShape) {
      lines.push('Request:', '', '```', ...shapeKeys(row.requestShape).slice(0, 40), '```', '');
    }
    if (row.responseShape) {
      lines.push('Response:', '', '```', ...shapeKeys(row.responseShape).slice(0, 40), '```', '');
    }
  }

  lines.push('## Specification discovery', '');
  if (spec) {
    lines.push(`A machine-readable specification answered at \`${spec.url}\`.`, '');
    lines.push(`- Title: ${spec.title || 'unnamed'}`);
    lines.push(`- Documented paths: ${spec.paths.length}`);
    lines.push('', '| Path | Methods |', '| --- | --- |');
    for (const entry of spec.paths.slice(0, 200)) {
      lines.push(`| \`${entry.path}\` | ${entry.methods.join(', ')} |`);
    }
  } else {
    lines.push('No OpenAPI or Swagger document answered at the probed locations, so this');
    lines.push('report is built entirely from observed traffic. That is a record of what the');
    lines.push('application calls, not a promise of everything the server accepts.');
  }
  return lines.join('\n') + '\n';
}

export async function renderReports({ outDir, profile }) {
  const screens = await loadScreens(outDir);
  const statePath = join(outDir, 'crawl-state.json');
  const state = existsSync(statePath) ? JSON.parse(await readFile(statePath, 'utf8')) : { visited: {}, failed: {} };
  const networkPath = join(outDir, 'network.json');
  const network = existsSync(networkPath) ? JSON.parse(await readFile(networkPath, 'utf8')) : [];
  const specPath = join(outDir, 'openapi-discovery.json');
  const spec = existsSync(specPath) ? JSON.parse(await readFile(specPath, 'utf8')) : null;

  await writeFile(join(outDir, 'SCREEN-INVENTORY.md'), renderInventory(screens, state, profile));
  await writeFile(join(outDir, 'COMPONENT-ANALYSIS.md'), renderComponents(screens, profile));
  await writeFile(join(outDir, 'LOCATOR-STRATEGY.md'), renderLocators(screens, profile));
  await writeFile(join(outDir, 'API-DOCUMENTATION.md'), renderApi(network, spec && spec.found ? spec : null, profile));
  return { screens: screens.length, endpoints: network.length };
}
