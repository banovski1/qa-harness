#!/usr/bin/env node
// Skill C — Skill B's routes joined to a base URL. Pure string composition: no request is fired
// and no sample id is invented, so a dynamic segment stays a visible placeholder.
//
//   node scripts/repo-analyzer/live-urls.mjs [--base-url https://…] [--path-prefix /web/index.php]

import fs from 'node:fs';
import path from 'node:path';
import {loadProjectConfig} from '../project-config.js';
import {ANALYSIS_DIR, outPath, reportWritten, table, writeReport} from './report.mjs';
import {REPO_ROOT, parseArgs, readJson, rel} from './util.mjs';

/** The base URL the rest of the repo already targets, unless the caller names another. */
function defaultBaseUrl() {
  try {
    return loadProjectConfig().baseUrl;
  } catch {
    return null;
  }
}

export function joinUrl(baseUrl, prefix, routePath) {
  const base = String(baseUrl).replace(/\/+$/, '');
  const middle = prefix ? `/${String(prefix).replace(/^\/+|\/+$/g, '')}` : '';
  const route = routePath === '/' ? '/' : `/${String(routePath).replace(/^\/+/, '')}`;
  return `${base}${middle}${route}`.replace(/([^:])\/{2,}/g, '$1/');
}

function render(source, baseUrl, prefix, rows) {
  const withParams = rows.filter((row) => row.params.length > 0);
  return [
    '# Live URLs',
    '',
    '<!-- Generated by scripts/repo-analyzer — do not hand-edit; re-run the analyzer instead. -->',
    '',
    `- **App**: \`${source.app}\``,
    `- **Base URL**: ${baseUrl}`,
    `- **Path prefix**: ${prefix ? `\`${prefix}\`` : 'none'}`,
    `- **Routes**: ${rows.length} (from \`${source.from}\`, strategy: ${source.strategy ?? 'none'})`,
    `- **Generated**: ${new Date().toISOString()}`,
    '',
    table(['URL', 'Placeholders', 'Renders'], rows.map((row) => [
      row.params.length > 0 ? row.url : `[${row.url}](${row.url})`,
      row.params.length > 0 ? row.params.map((p) => `\`{${p}}\``).join(', ') : null,
      row.component ? `\`${row.component}\`` : null,
    ])),
    '',
    '## Placeholders',
    '',
    withParams.length === 0
      ? 'Every route is static — each URL above can be opened as written.'
      : `${withParams.length} URL(s) carry a dynamic segment. The placeholder is left intact: no sample id is invented here, because a wrong one reads as a real URL and fails confusingly. Fill them from a precondition step (see \`analysis/api-documentation.md\`).`,
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = parseArgs();
  const routesFile = args.routes ? path.resolve(REPO_ROOT, String(args.routes)) : path.join(ANALYSIS_DIR, 'pages-and-routes.json');
  if (!fs.existsSync(routesFile)) {
    throw new Error(`No route data at ${rel(REPO_ROOT, routesFile)} — run scripts/repo-analyzer/routes.mjs first.`);
  }
  const source = readJson(routesFile);
  const baseUrl = args.baseUrl ? String(args.baseUrl) : defaultBaseUrl();
  if (!baseUrl) {
    throw new Error('No base URL: pass --base-url, or set baseUrl: in app-config.yaml.');
  }
  const prefix = args.pathPrefix ? String(args.pathPrefix) : '';
  const rows = source.routes
    .map((route) => ({...route, url: joinUrl(baseUrl, prefix, route.path)}))
    .sort((a, b) => a.url.localeCompare(b.url));
  const written = writeReport({
    outFile: outPath(args, 'live-urls.md'),
    body: render({app: source.app, strategy: source.strategy, from: rel(REPO_ROOT, routesFile)}, baseUrl, prefix, rows),
    data: {app: source.app, baseUrl, pathPrefix: prefix, urls: rows.map((r) => ({url: r.url, params: r.params, component: r.component}))},
    dryRun: Boolean(args.dryRun),
  });
  reportWritten(written, [`${rows.length} URL(s) from ${baseUrl}${prefix}`]);
}

export {render as renderLiveUrls};
